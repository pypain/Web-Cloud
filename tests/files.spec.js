import { test, expect } from '@playwright/test';
test('files persist, preview, rename, move, trash and restore', async ({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Мои файлы',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Новая папка',exact:true}).click();
 await page.getByLabel('Название',{exact:true}).fill('Работа');
 await page.getByRole('button',{name:'Создать папку'}).click();
 await expect(page.locator('.file-name').filter({hasText:'Работа'})).toBeVisible();
 await page.locator('#file-input').setInputFiles({name:'test.txt',mimeType:'text/plain',buffer:Buffer.from('Проверка содержимого файла')});
 await page.locator('.file-name').filter({hasText:'test.txt'}).click();
 await expect(page.locator('#text-preview')).toHaveText('Проверка содержимого файла');
 await page.getByLabel('Закрыть предпросмотр').click();
 await page.reload();
 await page.getByLabel('Действия: test.txt',{exact:true}).click();
 await page.getByRole('menuitem',{name:'Переименовать'}).click();
 await page.getByLabel('Название',{exact:true}).fill('Отчёт.txt');
 await page.getByRole('button',{name:'Сохранить',exact:true}).click();
 await page.getByLabel('Действия: Отчёт.txt',{exact:true}).click();
 await page.getByRole('menuitem',{name:'Переместить'}).click();
 await page.getByLabel('Папка',{exact:true}).selectOption({label:'Работа'});
 await page.locator('#confirm-move').click();
 await page.locator('.file-name').filter({hasText:'Работа'}).click();
 await expect(page.locator('.file-name').filter({hasText:'Отчёт.txt'})).toBeVisible();
 await page.getByLabel('Действия: Отчёт.txt',{exact:true}).click();
 await page.getByRole('menuitem',{name:'Поделиться'}).click();
 await expect(page.getByRole('dialog')).toContainText('после подключения серверного хранилища');
 await page.getByRole('button',{name:'Подготовить к обмену'}).click();
 await page.locator('[data-nav="links"]').click();
 await expect(page.locator('.file-name').filter({hasText:'Отчёт.txt'})).toBeVisible();
 await page.getByLabel('Действия: Отчёт.txt',{exact:true}).click();
 await page.getByRole('menuitem',{name:'В корзину'}).click();
 await page.locator('[data-nav="trash"]').click();
 await page.getByLabel('Действия: Отчёт.txt',{exact:true}).click();
 await page.getByRole('menuitem',{name:'Восстановить'}).click();
 await expect(page.getByRole('heading',{name:'Корзина пуста'})).toBeVisible();
 await page.locator('[data-nav="files"]').click();
 await page.getByPlaceholder('Поиск файлов и папок').fill('Отчёт');
 await expect(page.locator('.file-row')).toHaveCount(1);
 const download=page.waitForEvent('download');
 await page.getByLabel('Действия: Отчёт.txt',{exact:true}).click();
 await page.getByRole('menuitem',{name:'Скачать'}).click();
 expect((await download).suggestedFilename()).toBe('Отчёт.txt');
 expect(errors).toEqual([]);
});
