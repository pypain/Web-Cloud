test('folder descendants, duplicate names, grid and permanent deletion',async({page})=>{
 await page.goto('/');
 await page.locator('.file-name').filter({hasText:'Документы'}).click();
 const file={name:'a.txt',mimeType:'text/plain',buffer:Buffer.from('abc')};
 await page.locator('#file-input').setInputFiles(file);
 await page.locator('#file-input').setInputFiles(file);
 await expect(page.locator('.file-row')).toHaveCount(2);
 await expect(page.locator('.file-name').filter({hasText:'a (1).txt'})).toBeVisible();
 await page.getByLabel('Плитки',{exact:true}).click();
 await expect(page.locator('.file-items')).toHaveClass(/grid/);
 await page.locator('[data-folder=""]').click();
 await page.getByLabel('Действия: Документы',{exact:true}).click();
 await page.getByRole('menuitem',{name:'В корзину'}).click();
 await page.getByPlaceholder('Поиск файлов и папок').fill('a.txt');
 await expect(page.locator('.file-row')).toHaveCount(0);
 await page.locator('[data-nav="trash"]').click();
 await expect(page.locator('.file-row')).toHaveCount(1);
 await page.getByLabel('Действия: Документы',{exact:true}).click();
 await page.getByRole('menuitem',{name:'Восстановить'}).click();
 await page.locator('[data-nav="files"]').click();
 await page.locator('.file-name').filter({hasText:'Документы'}).click();
 await expect(page.locator('.file-row')).toHaveCount(2);
 await page.getByLabel('Выбрать все файлы',{exact:true}).check();
 await page.locator('.selection-actions [data-action="trash"]').click();
 await page.locator('[data-nav="trash"]').click();
 await page.getByRole('button',{name:'Очистить корзину'}).click();
 await page.getByRole('button',{name:'Удалить навсегда',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Корзина пуста'})).toBeVisible();
 await page.reload();await expect(page.locator('.file-row')).toHaveCount(4);
});
